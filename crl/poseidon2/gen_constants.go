//go:build ignore

// Writes constants.go from spec/vectors/poseidon2-constants.json.
//
//	go generate ./crl/poseidon2
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"log"
	"os"
)

func main() {
	raw, err := os.ReadFile("../../spec/vectors/poseidon2-constants.json")
	if err != nil {
		log.Fatal(err)
	}
	var c struct {
		InternalD []string   `json:"internal_d"`
		FirstFull [][]string `json:"round_constants_first_full"`
		Partial   []string   `json:"round_constants_partial"`
		LastFull  [][]string `json:"round_constants_last_full"`
	}
	if err := json.Unmarshal(raw, &c); err != nil {
		log.Fatal(err)
	}
	var b bytes.Buffer
	fmt.Fprintln(&b, "// Code generated by gen_constants.go from spec/vectors/poseidon2-constants.json. DO NOT EDIT.")
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "package poseidon2")
	fmt.Fprintln(&b)
	row := func(xs []string) {
		fmt.Fprint(&b, "{")
		for _, x := range xs {
			fmt.Fprintf(&b, "%q, ", x)
		}
		fmt.Fprint(&b, "}")
	}
	fmt.Fprint(&b, "var internalDHex = [4]string")
	row(c.InternalD)
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "var firstFullHex = [4][4]string{")
	for _, r := range c.FirstFull {
		row(r)
		fmt.Fprintln(&b, ",")
	}
	fmt.Fprintln(&b, "}")
	fmt.Fprintln(&b, "var partialHex = [56]string{")
	for _, x := range c.Partial {
		fmt.Fprintf(&b, "%q,\n", x)
	}
	fmt.Fprintln(&b, "}")
	fmt.Fprintln(&b, "var lastFullHex = [4][4]string{")
	for _, r := range c.LastFull {
		row(r)
		fmt.Fprintln(&b, ",")
	}
	fmt.Fprintln(&b, "}")
	out, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("constants.go", out, 0o644); err != nil {
		log.Fatal(err)
	}
}
